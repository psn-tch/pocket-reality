#!/usr/bin/env python3
"""Bakes Chicago Kare (MIT, by Duane King) into a 1-bit C font table.

Usage: make-font.py font.ttf pointsize out.h
"""
import subprocess
import sys

CANVAS_W = 22
CANVAS_H = 18
BASELINE = 13
MAX_W = 16


def run(*args):
    return subprocess.run(["magick", *args], capture_output=True, check=True).stdout


def label_width(ttf, size, text):
    fmt = run("-background", "white", "-fill", "black", "-font", ttf, "-pointsize", str(size),
              "+antialias", "label:" + text.replace("\\", "\\\\").replace("%", "%%"),
              "-format", "%w", "info:")
    return int(fmt)


def advance(ttf, size, ch):
    """Width added by ch between two bars, which also measures the space."""
    return label_width(ttf, size, "|" + ch + "|") - label_width(ttf, size, "||")


def glyph_rows(ttf, size, ch):
    text = {"\\": "\\\\", "%": "%%"}.get(ch, ch)
    raw = run("-size", f"{CANVAS_W}x{CANVAS_H}", "xc:white", "-font", ttf, "-pointsize", str(size),
              "+antialias", "-fill", "black", "-annotate", f"+1+{BASELINE}", text,
              "-depth", "8", "gray:-")
    rows = []
    for y in range(CANVAS_H):
        bits = 0
        for x in range(MAX_W):
            if raw[y * CANVAS_W + x + 1] < 128:
                bits |= 1 << x
        rows.append(bits)
    return rows


def main():
    ttf, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    lines = [
        "/* Generated by scripts/make-font.py from Chicago Kare, MIT, Copyright (c) 2024 Duane King. */",
        f"#define FONT_HEIGHT {CANVAS_H}",
        f"#define FONT_BASELINE {BASELINE}",
        "static const unsigned char font_width[95] = {",
    ]
    widths = []
    table = []
    for code in range(32, 127):
        ch = chr(code)
        widths.append(advance(ttf, size, ch))
        rows = [0] * CANVAS_H if ch == " " else glyph_rows(ttf, size, ch)
        table.append("\t{" + ",".join(f"0x{r:x}" for r in rows) + "},")
    lines.append("\t" + ",".join(map(str, widths)))
    lines.append("};")
    lines.append(f"static const unsigned short font_bits[95][{CANVAS_H}] = {{")
    lines.extend(table)
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("widths", min(widths), max(widths))


main()
